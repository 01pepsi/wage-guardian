def _tokens(text):
    return set(re.findall(r"[가-힣A-Za-z0-9]+", text.lower()))


def search_law(query: str, k: int = 4):
    """질문과 관련된 조문 top-k. 결과의 id만 답변에 인용할 수 있다."""
    q = query.lower()
    q_nospace = q.replace(" ", "")
    q_tokens = _tokens(query)
    scored = []
    for law in LAWS:
        score = 0
        if law["id"].replace(" ", "").lower() in q_nospace:  # 조문 번호를 직접 언급하면 우선
            score += 10
        for kw in law["keywords"]:
            if kw.lower() in q:
                score += 3
        score += len(q_tokens & _tokens(law["title"] + " " + law["text"]))
        if score > 0:
            scored.append((score, law))
    scored.sort(key=lambda x: -x[0])
    return [{"id": l["id"], "title": l["title"], "text": l["text"]} for _, l in scored[:k]]


